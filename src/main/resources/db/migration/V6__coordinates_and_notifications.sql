ALTER TABLE incident ADD COLUMN latitude DOUBLE PRECISION;
ALTER TABLE incident ADD COLUMN longitude DOUBLE PRECISION;
CREATE INDEX idx_incident_coordinates ON incident(latitude, longitude);

CREATE TABLE user_notification (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
  incident_id BIGINT REFERENCES incident(id) ON DELETE CASCADE,
  type VARCHAR(30) NOT NULL,
  title VARCHAR(160) NOT NULL,
  body VARCHAR(500) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  read_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_notification_user_created ON user_notification(user_id, created_at);
