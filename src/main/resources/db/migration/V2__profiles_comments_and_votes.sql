ALTER TABLE app_user ADD COLUMN full_name VARCHAR(80) NOT NULL DEFAULT 'CityConnect User';

CREATE TABLE incident_comment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id BIGINT NOT NULL REFERENCES incident(id) ON DELETE CASCADE,
  author_id BIGINT NOT NULL REFERENCES app_user(id),
  body VARCHAR(1000) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_incident_comment_incident_created ON incident_comment(incident_id, created_at);

CREATE TABLE incident_vote (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id BIGINT NOT NULL REFERENCES incident(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES app_user(id),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_incident_vote_user UNIQUE (incident_id, user_id)
);
CREATE INDEX idx_incident_vote_incident ON incident_vote(incident_id);
