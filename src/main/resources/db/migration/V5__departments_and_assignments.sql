CREATE TABLE department (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  description VARCHAR(500),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE app_user ADD COLUMN department_id BIGINT REFERENCES department(id);
ALTER TABLE incident ADD COLUMN department_id BIGINT REFERENCES department(id);
ALTER TABLE incident ADD COLUMN assigned_employee_id BIGINT REFERENCES app_user(id);
CREATE INDEX idx_incident_assignment ON incident(department_id, assigned_employee_id);

CREATE TABLE incident_internal_note (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id BIGINT NOT NULL REFERENCES incident(id) ON DELETE CASCADE,
  author_id BIGINT NOT NULL REFERENCES app_user(id),
  body VARCHAR(2000) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_incident_note_incident ON incident_internal_note(incident_id, created_at);
